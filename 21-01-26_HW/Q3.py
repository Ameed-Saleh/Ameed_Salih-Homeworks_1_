'''
קלוט מספרים מהמשתמש בלולאה
הקליטה תימשך עד שייקלט המספר ‎-999

בסיום הדפס:

כמה מספרים נקלטו (לא כולל -999)
מה סכום כל המספרים שנקלטו (לא כולל -999)
'''

# שאלה 3 – קלט עד 999-


sum = 0
i = 0
numbers: int = int(input(" enter a number: "))
while numbers != -999 :
    sum += numbers
    i += 1
    numbers: int = int(input(" enter a number: "))

print(" סכום המספרים שנקלטו הוא:",sum )
print( " מספר המספרים שנקלטו הינו:",i  , "לא כולל המספר 999-")

